#!/usr/bin/env node
/**
 * Checks the SKILL.md frontmatter of every agent skill suite in this repository.
 *
 * Agent harnesses discover project skills by walking for `.agents/skills`
 * directories (`.claude/skills` is the tracked content here, reached through
 * the committed `.agents/skills` symlink) and reading each skill's `SKILL.md`
 * per the Agent Skills specification. A `SKILL.md` whose frontmatter does not
 * parse is skipped whole: the skill is absent from the harness's listing with
 * only a startup warning, so a session never learns the procedure exists and
 * nothing about the change looks like a failure.
 *
 * The trigger that bites most is a `description:` written as a plain YAML
 * scalar containing ": " — YAML reads that as a nested mapping and rejects the
 * entire frontmatter block. Writing the value as a folded block scalar
 * (`description: >-` with indented continuation lines, the style most of these
 * suites already use) carries the same text and cannot collide that way.
 *
 * What this check fails on is therefore the frontmatter that silently drops a
 * skill, plus the name/description requirements the specification states. The
 * 1024-character description limit is reported and not enforced: a long
 * description still loads, and shrinking one is a routing-text decision rather
 * than a correctness one. Pass --strict-description-length to enforce it.
 *
 * Out of scope by design: a skill tree that is not under `.agents` or
 * `.claude` — `packages/boxel-cli/plugin/skills/` is a Claude Code plugin's own
 * skill set, authored and regenerated by that package — and a suite owned by
 * another repository or published as realm content.
 *
 * Usage:
 *   node scripts/check-skill-frontmatter.mjs [--fix] [--strict-description-length] [--list-long]
 *
 * --fix rewrites an offending plain scalar as a folded scalar holding the same
 * text. It changes nothing else in the file.
 */

import {
  existsSync,
  readdirSync,
  readFileSync,
  realpathSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// The directories a harness or this repository's own agent code reads a skill
// suite from: a `skills` directory under `.agents` or `.claude` (what pi and
// Codex walk for, and what Claude Code reads), including the named variant the
// Software Factory loads itself (`.agents/skills-orchestrator`).
const SUITE_PARENT_DIRS = new Set(['.agents', '.claude']);
const SUITE_DIR_RE = /^skills(-[a-z0-9]+)*$/;

// Not part of any suite: dependencies, build output, and generated trees.
const SKIP_DIRS = new Set([
  'node_modules',
  '.git',
  'dist',
  'declarations',
  'coverage',
  'bench-fixtures',
  '.boxel-skills-cache',
  '.output',
  'tmp',
]);

const NAME_MAX = 64;
const DESCRIPTION_MAX = 1024;
const NAME_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
// A plain scalar cannot hold these without YAML reading structure instead.
const LEADING_INDICATORS = /^[*&!@`]/;
const WRAP_AT = 76;
// Marks the one problem --fix can repair, so the fix pass and the report agree
// on which message it means.
const PLAIN_SCALAR_MARKER = 'plain scalar containing ": "';

const argv = process.argv.slice(2);
const fix = argv.includes('--fix');
const strictLength = argv.includes('--strict-description-length');
const listLong = argv.includes('--list-long');

function isDirectory(path) {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

/**
 * Every skill suite in the repository, keyed by its real path so a suite
 * reached twice — through a symlink and through its target — counts once. A
 * suite that stops being a symlink of its sibling is scanned twice instead,
 * and the duplicate-name check below reports exactly that.
 */
function findSuites(dir, suites = new Map()) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return suites;
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const path = join(dir, entry.name);
    if (!isDirectory(path)) continue;
    // A directory with its own `.git` is another repository checked out inside
    // this one — the catalog clones under `packages/catalog/`, say. Its
    // frontmatter belongs to that repository's own checks.
    if (existsSync(join(path, '.git'))) continue;
    if (SUITE_PARENT_DIRS.has(entry.name)) {
      // Only a suite a session can actually be rooted at: one owned by the
      // repository or by one of its packages. A `.agents/skills` inside realm
      // content or a test fixture is a published copy of somebody else's tree,
      // not a suite this repository runs.
      if (isSuiteOwner(dir)) {
        for (const child of readdirSync(path, { withFileTypes: true })) {
          if (!SUITE_DIR_RE.test(child.name)) continue;
          const suite = join(path, child.name);
          if (!isDirectory(suite)) continue;
          const real = realpathSync(suite);
          const found = suites.get(real) ?? { real, paths: [] };
          found.paths.push(relative(REPO_ROOT, suite));
          suites.set(real, found);
        }
      }
      continue;
    }
    findSuites(path, suites);
  }
  return suites;
}

/**
 * True when `dir` is the repository root or one of its packages — the owners
 * that can hold a suite a harness or this repository's agent code loads.
 */
function isSuiteOwner(dir) {
  if (resolve(dir) === REPO_ROOT) return true;
  const parts = relative(REPO_ROOT, dir).split('/');
  return parts.length === 2 && parts[0] === 'packages';
}

/**
 * The skill directories of one suite, following the discovery rule the
 * harnesses use: a directory holding SKILL.md is a skill and is not descended
 * into, so a skill's own `references/` never counts as a skill of its own.
 */
function findSkills(dir, out = []) {
  if (existsSync(join(dir, 'SKILL.md'))) {
    out.push(dir);
    return out;
  }
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const path = join(dir, entry.name);
    if (isDirectory(path)) findSkills(path, out);
  }
  return out;
}

/**
 * Reads the frontmatter block as the flat key/value map these files use,
 * reporting the constructs that make YAML reject the block instead of reading
 * the value. Returns the fields and every problem found in the block.
 */
function readFrontmatter(text) {
  const errors = [];
  const lines = text.split(/\r?\n/);
  if (lines[0] !== '---') {
    return {
      fields: null,
      errors: ['the file does not open with a `---` frontmatter delimiter'],
    };
  }
  const end = lines.findIndex((line, index) => index > 0 && line === '---');
  if (end === -1) {
    return {
      fields: null,
      errors: ['the frontmatter block is never closed by a `---` line'],
    };
  }
  const block = lines.slice(1, end);
  const fields = new Map();
  // How each value was written, since only a plain scalar can be mistaken for
  // structure: a block scalar, a quoted scalar and a flow collection each hold
  // their text as data.
  const styles = new Map();
  // Which key a folded block scalar or a continued plain scalar belongs to.
  let openKey = null;
  let openFolded = false;

  for (let index = 0; index < block.length; index++) {
    const line = block[index];
    const displayLine = index + 2; // 1-based, counting the opening `---`

    if (line.trim() === '') {
      continue;
    }

    if (/^\s/.test(line)) {
      if (openKey === null) {
        errors.push(
          `line ${displayLine}: an indented line with no key above it`,
        );
        continue;
      }
      const value = fields.get(openKey);
      if (openFolded) {
        fields.set(openKey, `${value} ${line.trim()}`.trim());
      } else {
        // YAML folds a more-indented continuation into the plain scalar with a
        // single space. Read it the same way, then judge the joined value.
        fields.set(openKey, `${value} ${line.trim()}`);
      }
      continue;
    }

    const entry = /^([A-Za-z][A-Za-z0-9-]*):(?:[ \t]+(.*))?$/.exec(line);
    if (!entry) {
      errors.push(
        `line ${displayLine}: not a \`key: value\` frontmatter entry: ${line.slice(0, 60)}`,
      );
      openKey = null;
      openFolded = false;
      continue;
    }

    const [, key, rest = ''] = entry;
    if (fields.has(key))
      errors.push(`line ${displayLine}: duplicate key \`${key}\``);
    const raw = rest.trim();

    if (raw === '') {
      fields.set(key, '');
      styles.set(key, 'plain');
      openKey = key;
      openFolded = false;
      continue;
    }

    if (/^[>|]/.test(raw)) {
      fields.set(key, '');
      styles.set(key, 'block');
      openKey = key;
      openFolded = raw.startsWith('>');
      continue;
    }

    if (raw.startsWith('"') || raw.startsWith("'")) {
      const quote = raw[0];
      let closed = false;
      for (let i = 1; i < raw.length; i++) {
        if (raw[i] === '\\') {
          i++;
          continue;
        }
        if (raw[i] === quote) {
          closed = true;
          break;
        }
      }
      if (!closed) {
        errors.push(
          `line ${displayLine}: \`${key}\` opens a ${quote === '"' ? 'double' : 'single'}-quoted value that never closes on the same line; write it as a folded scalar (\`${key}: >-\`) instead`,
        );
        fields.set(key, raw.slice(1));
        styles.set(key, 'quoted');
        openKey = null;
        openFolded = false;
        continue;
      }
      fields.set(key, raw.slice(1, -1));
      styles.set(key, 'quoted');
      openKey = null;
      openFolded = false;
      continue;
    }

    if (raw.startsWith('[') || raw.startsWith('{')) {
      let depth = 0;
      let cursor = index;
      while (cursor < block.length) {
        for (const char of block[cursor]) {
          if (char === '[' || char === '{') depth++;
          if (char === ']' || char === '}') depth--;
        }
        if (depth <= 0) break;
        cursor++;
      }
      if (depth > 0) {
        errors.push(
          `line ${displayLine}: \`${key}\` opens a flow collection that never closes inside the frontmatter block`,
        );
      }
      fields.set(key, raw);
      styles.set(key, 'flow');
      openKey = null;
      openFolded = false;
      index = cursor;
      continue;
    }

    if (LEADING_INDICATORS.test(raw)) {
      errors.push(
        `line ${displayLine}: \`${key}\` opens with \`${raw[0]}\`, which YAML reads as an anchor, alias, tag or reserved character`,
      );
    }
    fields.set(key, raw);
    styles.set(key, 'plain');
    openKey = key;
    openFolded = false;
  }

  // A plain scalar holding ": " is where YAML stops reading a scalar and looks
  // for a nested mapping, and the whole block is refused. A " # truncates the
  // value at the comment instead, which is worse: the skill loads with half a
  // description. Neither happens inside a block scalar, where the text is data.
  for (const [key, value] of fields) {
    if (!value || styles.get(key) !== 'plain') continue;
    const colon = value.indexOf(': ');
    if (colon !== -1) {
      errors.push(
        `${PLAIN_SCALAR_MARKER}: line ${lineOf(block, key) ?? '?'}: \`${key}\` is a plain scalar containing ": " — YAML reads it as a nested mapping and refuses the whole frontmatter block, so this skill never loads. Write it as \`${key}: >-\` with the text on indented continuation lines. First offender: "…${value.slice(colon, colon + 40)}…"`,
      );
    }
    const comment = value.indexOf(' #');
    if (comment !== -1) {
      errors.push(
        `line ${lineOf(block, key) ?? '?'}: \`${key}\` contains " #", which YAML starts a comment at — the value is silently truncated to "…${value.slice(0, Math.min(comment, 40))}". Write it as \`${key}: >-\` or quote it.`,
      );
    }
  }

  return { fields, errors };
}

function lineOf(block, key) {
  const index = block.findIndex((l) => new RegExp(`^${key}:`).test(l));
  return index === -1 ? null : index + 2;
}

/** The plain scalar of `key` as written on its own line, for --fix. */
function plainScalarLine(block, key) {
  const index = block.findIndex(
    (l) =>
      new RegExp(`^${key}: `).test(l) &&
      !/^[A-Za-z][A-Za-z0-9-]*:[ \t]*[>"'|']/.test(l),
  );
  return index === -1
    ? null
    : { index, value: block[index].replace(new RegExp(`^${key}: `), '') };
}

function foldLines(value) {
  const words = value.split(/\s+/);
  const lines = [];
  let line = '';
  for (const word of words) {
    if (line && line.length + 1 + word.length > WRAP_AT) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

function rewriteAsFolded(text, key) {
  const lines = text.split(/\r?\n/);
  const end = lines.findIndex((line, index) => index > 0 && line === '---');
  if (end === -1) return null;
  const block = lines.slice(1, end);
  const found = plainScalarLine(block, key);
  if (!found) return null;
  const replacement = [
    `${key}: >-`,
    ...foldLines(found.value).map((l) => `  ${l}`),
  ];
  const rebuilt = [
    ...block.slice(0, found.index),
    ...replacement,
    ...block.slice(found.index + 1),
  ];
  return [lines[0], ...rebuilt, ...lines.slice(end)].join('\n');
}

const suites = findSuites(REPO_ROOT);

function scan() {
  const problems = [];
  const longDescriptions = [];
  let skillCount = 0;

  for (const suite of [...suites.values()].sort((a, b) =>
    a.paths[0].localeCompare(b.paths[0]),
  )) {
    const skillDirs = findSkills(suite.real).sort();
    if (skillDirs.length === 0) {
      problems.push({
        file: suite.paths.join(' + '),
        messages: ['this suite holds no SKILL.md'],
      });
      continue;
    }
    // Names are unique per suite: that is the scope a harness resolves a skill
    // name in, and the Software Factory deliberately keeps same-named skills
    // in separate suites that different runtimes load.
    const names = new Map();
    for (const skillDir of skillDirs) {
      skillCount++;
      const file = join(skillDir, 'SKILL.md');
      const display = relative(REPO_ROOT, file);
      const directory = basename(skillDir);
      const messages = [];

      let text;
      try {
        text = readFileSync(file, 'utf-8');
      } catch (error) {
        problems.push({
          file: display,
          messages: [`cannot read: ${error.message}`],
        });
        continue;
      }

      const { fields, errors } = readFrontmatter(text);
      messages.push(...errors);

      if (fields) {
        const name = fields.get('name');
        const description = fields.get('description');

        if (!name || name.trim() === '') {
          messages.push(
            'no `name:` — a harness falls back to the directory name, and readers that require the field skip the skill',
          );
        } else {
          if (!NAME_RE.test(name))
            messages.push(
              `name "${name}" must be lowercase letters, digits and single hyphens`,
            );
          if (name.length > NAME_MAX)
            messages.push(
              `name "${name}" is ${name.length} characters (max ${NAME_MAX})`,
            );
          if (name !== directory)
            messages.push(
              `name "${name}" does not match its directory "${directory}"`,
            );
          const seen = names.get(name);
          if (seen)
            messages.push(
              `name "${name}" collides with ${seen} — a harness keeps one of the two and drops this skill`,
            );
          else names.set(name, display);
        }

        if (!description || description.trim() === '') {
          messages.push(
            'no `description:` — a harness loads no skill without one',
          );
        } else if (description.length > DESCRIPTION_MAX) {
          longDescriptions.push({
            display,
            name: fields.get('name') ?? directory,
            length: description.length,
          });
        }

        const flag = fields.get('disable-model-invocation');
        if (flag !== undefined && flag !== 'true' && flag !== 'false') {
          messages.push(
            `disable-model-invocation must be true or false, found "${flag}"`,
          );
        }
      }

      if (messages.length) problems.push({ file: display, messages });
    }
  }

  return { problems, longDescriptions, skillCount };
}

// --fix rewrites the one problem class that has a mechanical repair: a plain
// scalar description, folded so its colons stop being structure. The tree is
// scanned again afterwards, so what gets reported is the tree as written.
let repaired = 0;
let result = scan();
if (fix) {
  for (const problem of result.problems) {
    if (
      !problem.messages.some((message) =>
        message.startsWith(PLAIN_SCALAR_MARKER),
      )
    )
      continue;
    const rewritten = rewriteAsFolded(
      readFileSync(join(REPO_ROOT, problem.file), 'utf-8'),
      'description',
    );
    if (!rewritten) continue;
    writeFileSync(join(REPO_ROOT, problem.file), rewritten);
    repaired++;
    console.log(`rewrote description as a folded scalar: ${problem.file}`);
  }
  if (repaired) result = scan();
}

const { problems, longDescriptions, skillCount } = result;

if (longDescriptions.length > 0) {
  const longest = [...longDescriptions].sort((a, b) => b.length - a.length);
  console.log(
    `note: ${longDescriptions.length} of ${skillCount} descriptions exceed the ${DESCRIPTION_MAX}-character Agent Skills limit ` +
      `(largest: ${longest[0].name} ${longest[0].length}). They still load; the cost is prompt size, not a dropped skill. ` +
      `Enforce the limit with --strict-description-length.`,
  );
  if (listLong) {
    for (const entry of longest)
      console.log(`  ${String(entry.length).padStart(5)}  ${entry.display}`);
  }
}

if (problems.length > 0) {
  console.log(
    `\n${problems.length} SKILL.md file(s) a harness would not load:`,
  );
  for (const problem of problems) {
    console.log(`  ${problem.file}`);
    for (const message of problem.messages)
      console.log(`      ${message.replace(`${PLAIN_SCALAR_MARKER}: `, '')}`);
  }
}

console.log(
  `\nchecked ${skillCount} skills across ${suites.size} suite(s): ${[...suites.values()].map((s) => s.paths.join(' + ')).join(', ')}`,
);
if (fix) console.log(`rewritten: ${repaired}`);

const failed =
  problems.length > 0 || (strictLength && longDescriptions.length > 0);
process.exit(failed ? 1 : 0);
