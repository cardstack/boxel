function demoCard(demo) {
  return {
    data: {
      type: 'card',
      attributes: {
        demoId: demo.id,
        title: demo.title,
        group: demo.group,
        lede: demo.lede,
        sample: demo.sample,
        apis: demo.apis,
        cardInfo: { name: demo.title, summary: demo.lede },
      },
      relationships: {
        'cardInfo.theme': { links: { self: '../theme' } },
      },
      meta: { adoptsFrom: { module: '../site', name: 'ChoreoDemo' } },
    },
  };
}

function indexCard(catalog) {
  const relationships = {};
  catalog.forEach((demo, index) => {
    relationships[`demos.${index}`] = { links: { self: `./demos/${demo.id}` } };
  });
  return {
    data: {
      type: 'card',
      attributes: {
        headline: 'Motion, Choreographed.',
        cardInfo: {
          name: 'Choreo',
          summary:
            'The Motion engine for Ember — and a timeline for the scene.',
          cardThumbnailURL: './og.png',
        },
      },
      relationships: {
        ...relationships,
        'cardInfo.theme': { links: { self: './theme' } },
      },
      meta: { adoptsFrom: { module: './site', name: 'ChoreoGallery' } },
    },
  };
}

