/**
 * Deterministically generate the complete Boxel realm from the canonical
 * Choreo gallery package. Generated output is disposable; source edits live
 * in this package and the Ember harness consumes the same modules/assets.
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';
import ts from 'typescript';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, '..');
const repoRoot = resolve(packageRoot, '../..');
const outputRoot = join(packageRoot, 'dist-realm');
const runtimeEntry = join(packageRoot, 'dist/components/gallery-site.js');
const sourceCatalog = join(packageRoot, 'src/lib/catalog.ts');
const stylePath = join(packageRoot, 'styles/app.scoped.css');
const publicPath = join(repoRoot, 'packages/choreo-test-app/public');
const iframeBuild = join(packageRoot, 'dist-iframe');
const realmMediaRoot =
  process.env.CHOREO_REALM_MEDIA_ROOT ??
  'https://realms-staging.stack.cards/ctse/complex-macaw/';
const hostExternals = [
  /^@ember\//,
  /^@glimmer\/component$/,
  /^@glimmer\/tracking$/,
  /^@glimmer\/validator$/,
  /^ember-modifier$/,
];

if (!existsSync(runtimeEntry)) {
  throw new Error(
    'Missing package build. Run pnpm --filter choreo-gallery build first.',
  );
}

if (!process.argv.includes('--skip-iframe')) {
  buildIframeApp();
}

const catalog = await readCatalog();
if (!catalog.length) {
  throw new Error('The canonical gallery is empty');
}

rmSync(outputRoot, { recursive: true, force: true });
mkdirSync(join(outputRoot, 'builds'), { recursive: true });
mkdirSync(join(outputRoot, 'demos'), { recursive: true });

const runtimePlain = join(outputRoot, 'gallery-runtime.ts');
const runtimeStyles = join(outputRoot, 'gallery-runtime.css');
await esbuild.build({
  entryPoints: [join(packageRoot, 'dist/realm-entry.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['import', 'module', 'default'],
  splitting: false,
  // Boxel currently evaluates lazy dependency initializers through a classic
  // wrapper. Three 0.185 uses import.meta.url only to construct DRACO defaults;
  // both demos immediately replace those defaults with their realm asset path.
  // Give the initializer a classic-script-safe base without changing Vite.
  define: { 'import.meta.url': 'globalThis.location.href' },
  minifyIdentifiers: true,
  minifyWhitespace: true,
  minifySyntax: false,
  keepNames: false,
  sourcemap: false,
  outfile: runtimePlain,
  plugins: [
    {
      name: 'boxel-host-externals',
      setup(build) {
        build.onResolve({ filter: /.*/ }, (args) =>
          hostExternals.some((pattern) => pattern.test(args.path))
            ? { path: args.path, external: true }
            : null,
        );
      },
    },
  ],
  banner: {
    js: '// @ts-nocheck\n/* eslint-disable */\n// Generated by choreo-gallery/scripts/build-boxel-realm.mjs\n',
  },
});

const runtimeCode = readFileSync(runtimePlain, 'utf8');
assertRealmClean(runtimeCode);
const runtimeHash = digest(runtimeCode);
const runtimeName = `gallery-runtime-${runtimeHash}.ts`;
writeFileSync(join(outputRoot, 'builds', runtimeName), runtimeCode);
writeFileSync(
  runtimePlain,
  `/* eslint-disable */\nexport * from './builds/gallery-runtime-${runtimeHash}';\n`,
);

const css = [
  readFileSync(stylePath, 'utf8'),
  existsSync(runtimeStyles) ? readFileSync(runtimeStyles, 'utf8') : '',
].join('\n');
rmSync(runtimeStyles, { force: true });
writeFileSync(join(outputRoot, 'site.gts'), siteSource(css));
writeFileSync(
  join(outputRoot, 'index.json'),
  JSON.stringify(indexCard(catalog), null, 2),
);
writeFileSync(
  join(outputRoot, 'theme.json'),
  JSON.stringify(themeCard(), null, 2),
);
writeFileSync(
  join(outputRoot, 'realm.json'),
  JSON.stringify(realmConfig(catalog), null, 2),
);

for (const demo of catalog) {
  writeFileSync(
    join(outputRoot, 'demos', `${demo.id}.json`),
    JSON.stringify(demoCard(demo), null, 2),
  );
}

cpSync(publicPath, outputRoot, { recursive: true });
cpSync(
  join(publicPath, 'draco/draco_wasm_wrapper.js'),
  join(outputRoot, 'draco/draco_wasm_wrapper.txt'),
);
cpSync(join(packageRoot, 'public/icon.svg'), join(outputRoot, 'icon.svg'));
cpSync(iframeBuild, join(outputRoot, 'iframe'), { recursive: true });
// This target is the unlisted comparison site, not the public Pages build.
// Override the canonical site's permissive policy after copying its assets.
writeFileSync(join(outputRoot, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
// Native browser modules must not pass through Boxel's realm-module compiler,
// which rewrites fetch to import.meta.loader.fetch. .mjs is served verbatim
// with a JavaScript MIME type; keep Vite's chunk graph intact when renaming.
const browserAssets = join(outputRoot, 'iframe/assets');
const browserModules = readdirSync(browserAssets).filter((name) =>
  name.endsWith('.js'),
);
const rewriteBrowserModules = (source) =>
  browserModules.reduce(
    (text, name) => text.replaceAll(name, name.replace(/\.js$/, '.mjs')),
    source,
  );
for (const name of browserModules) {
  const source = rewriteBrowserModules(
    readFileSync(join(browserAssets, name), 'utf8'),
  );
  writeFileSync(join(browserAssets, name), source);
  renameSync(
    join(browserAssets, name),
    join(browserAssets, name.replace(/\.js$/, '.mjs')),
  );
}
const browserIndex = join(outputRoot, 'iframe/index.html');
writeFileSync(
  browserIndex,
  rewriteBrowserModules(readFileSync(browserIndex, 'utf8')),
);
/* Sagrada is consumed only by the isolated app under /iframe. Do not ship a
   second 8 MB copy at the realm root, and omit authoring/audition material
   that the film never requests. */
rmSync(join(outputRoot, 'sagrada.html'), { force: true });
rmSync(join(outputRoot, 'sagrada'), { recursive: true, force: true });
rmSync(join(outputRoot, 'iframe/sagrada/vo-audition'), {
  recursive: true,
  force: true,
});
rmSync(join(outputRoot, 'iframe/sagrada/README.md'), { force: true });
rmSync(join(outputRoot, 'iframe/sagrada/type-harness.html'), { force: true });
/* NLE plate + overlays are Ember-gallery media. Do not ship a second
   ~40 MB copy into the Boxel realm until that demo is catalogued there. */
rmSync(join(outputRoot, 'nle'), { recursive: true, force: true });

const manifest = {
  schemaVersion: 1,
  generatedBy: 'packages/choreo-gallery/scripts/build-boxel-realm.mjs',
  runtime: `builds/${runtimeName}`,
  runtimeSha256: createHash('sha256').update(runtimeCode).digest('hex'),
  demoCount: catalog.length,
  ids: catalog.map(({ id }) => id),
  iframeRoutes: ['_sylva', 'towers', 'sagrada'],
  mainDom: ['mockup', 'long-take'],
};
writeFileSync(
  join(outputRoot, 'gallery-manifest.generated'),
  JSON.stringify(manifest, null, 2),
);

if (process.argv.includes('--mirror')) {
  const config = JSON.parse(
    readFileSync(join(repoRoot, '.choreo-realm-sync.json'), 'utf8'),
  );
  const workspace = resolve(config.workspace);
  if (!workspace.endsWith('/stack.cards/ctse/complex-macaw')) {
    throw new Error(`Refusing to mirror to unexpected workspace: ${workspace}`);
  }
  const preserved = new Set(['.boxel-history', '.boxel-sync.json']);
  for (const entry of readdirSync(workspace)) {
    if (!preserved.has(entry)) {
      rmSync(join(workspace, entry), { recursive: true, force: true });
    }
  }
  cpSync(outputRoot, workspace, { recursive: true, force: true });
  console.log(`✓ mirrored generated realm → ${workspace}`);
}

console.log(`✓ generated ${catalog.length} demos in ${outputRoot}`);
console.log(
  `✓ runtime builds/${runtimeName} (${(runtimeCode.length / 1024).toFixed(1)} KB)`,
);

function buildIframeApp() {
  rmSync(iframeBuild, { recursive: true, force: true });
  const result = spawnSync(
    'pnpm',
    ['--filter', 'test-app', 'exec', 'vite', 'build', '--outDir', iframeBuild],
    {
      cwd: repoRoot,
      env: {
        ...process.env,
        APP_BASE: './',
        APP_LOCATION: 'hash',
        CHOREO_BOXEL_BUILD: '1',
      },
      stdio: 'inherit',
    },
  );
  if (result.error || result.status !== 0) {
    throw new Error(
      result.error?.message ?? `Iframe app build exited ${result.status}`,
    );
  }
}

async function readCatalog() {
  const source = readFileSync(sourceCatalog, 'utf8');
  const ast = ts.createSourceFile(
    sourceCatalog,
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  const removals = [];
  const bindings = new Set();
  for (const statement of ast.statements) {
    if (!ts.isImportDeclaration(statement)) {
      continue;
    }
    removals.push([statement.getFullStart(), statement.getEnd()]);
    const clause = statement.importClause;
    if (clause?.name) {
      bindings.add(clause.name.text);
    }
    const named = clause?.namedBindings;
    if (named && ts.isNamedImports(named)) {
      for (const element of named.elements) {
        bindings.add(element.name.text);
      }
    }
  }
  let body = source;
  for (const [start, end] of removals.reverse()) {
    body = body.slice(0, start) + body.slice(end);
  }
  const stubs = [...bindings].map((name) => `const ${name} = null;`).join('\n');
  const compiled = await esbuild.transform(`${stubs}\n${body}`, {
    loader: 'ts',
    format: 'esm',
    target: 'es2022',
  });
  const module = await import(
    `data:text/javascript;base64,${Buffer.from(compiled.code).toString('base64')}`
  );
  return module.createCatalog({
    SagradaStage: null,
    SylvaStage: null,
    TowerStage: null,
  });
}

function assertRealmClean(code) {
  const imports = [
    ...code.matchAll(/^import[^'"]*['"]([^'"]+)['"]/gm),
    ...code.matchAll(/^export[^'"]*from\s*['"]([^'"]+)['"]/gm),
  ].map((match) => match[1]);
  const unexpected = imports.filter(
    (specifier) =>
      specifier !== '@ember/template-compilation' &&
      !hostExternals.some((pattern) => pattern.test(specifier)),
  );
  if (unexpected.length || /\brequire\(/.test(code)) {
    throw new Error(
      `Runtime is not realm-clean: ${[...new Set(unexpected)].join(', ') || 'contains require()'}`,
    );
  }
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex').slice(0, 12);
}

