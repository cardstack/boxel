function realmConfig(catalog) {
  const rules = [
    { path: '/' },
    ...catalog.map(({ id }) => ({ path: `/${id}` })),
  ];
  const relationships = {};
  rules.forEach((_rule, index) => {
    relationships[`hostRoutingRules.${index}.instance`] = {
      links: { self: './index' },
    };
  });
  return {
    data: {
      type: 'card',
      attributes: {
        cardInfo: { name: 'Choreo' },
        iconURL: `${realmMediaRoot}icon.svg`,
        backgroundURL: `${realmMediaRoot}og.png`,
        hostRoutingRules: rules,
      },
      relationships,
      meta: {
        adoptsFrom: {
          module: 'https://cardstack.com/base/realm-config',
          name: 'RealmConfig',
        },
      },
    },
  };
}
