// Keeps usage-pages.test.gts in step with the usage pages on disk.
//   node scripts/usage-proof.mjs          fail when a page module is missing from the test
//   node scripts/usage-proof.mjs --write  regenerate the test
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TEST = join(root, 'usage-pages.test.gts');

// `boxel test` cannot load the surfaces bundles (its test server has no
// @ember/template-compilation), so a page whose imports reach surfaces/ is
// left out of the proof rather than failing the whole file.
const UNLOADABLE = /^surfaces\//;

function reaches(file, seen = new Set()) {
  if (seen.has(file)) return false;
  seen.add(file);
  if (UNLOADABLE.test(file)) return true;
  let text;
  try {
    text = readFileSync(join(root, file), 'utf8');
  } catch {
    return false;
  }
  for (let [, spec] of text.matchAll(/from '(\.{1,2}\/[^']+)'/g)) {
    let base = join(dirname(file), spec).replace(/\\/g, '/');
    for (let candidate of [base, `${base}.gts`, `${base}.ts`]) {
      try {
        readFileSync(join(root, candidate));
        if (reaches(candidate, seen)) return true;
        break;
      } catch {
        // try the next extension
      }
    }
  }
  return false;
}

function registries() {
  let sources = [
    ...readdirSync(join(root, 'components'))
      .filter((f) => f.endsWith('.usage.gts'))
      .map((f) => `components/${f}`),
    ...readdirSync(root).filter((f) => /^demo-.*\.gts$/.test(f)),
  ].sort();
  let out = [];
  for (let file of sources) {
    if (reaches(file)) continue;
    let text = readFileSync(join(root, file), 'utf8');
    for (let [, name] of text.matchAll(/^export const (DEMOS_\w+)/gm)) {
      out.push({ name, module: `./${file.replace(/\.gts$/, '')}` });
    }
  }
  return out;
}

function render(list) {
  let imports = list.map((r) => `import { ${r.name} } from '${r.module}';`).join('\n');
  let names = list.map((r) => `  ${r.name},`).join('\n');
  return `// Pretui — render proof: every usage page in the package mounts. Generated by
// \`node scripts/usage-proof.mjs --write\`; \`pnpm lint\` fails when a page module
// is missing from this list.
import { module, test } from 'qunit';
import { render } from '@ember/test-helpers';
import { setupCardTest } from '@cardstack/host/tests/helpers';
${imports}

/* eslint-disable @typescript-eslint/no-explicit-any -- the DEMOS registries
   are Record<string, unknown> by contract; mounting one requires the cast. */
type AnyComponent = any;

const REGISTRIES: Record<string, Record<string, unknown>> = {
${names}
};

module('Pretui | usage pages', function (hooks) {
  setupCardTest(hooks);
  for (let [registryName, registry] of Object.entries(REGISTRIES)) {
    for (let name of Object.keys(registry)) {
      test(\`\${registryName} · \${name} mounts\`, async function (assert) {
        let Demo = registry[name] as AnyComponent;
        assert.ok(Demo, \`\${name} present\`);
        await render(<template><Demo /></template>);
        assert.ok(document.querySelector('[data-test-pretui-usage]'), \`\${name} rendered a FreestyleUsage shell\`);
        assert.ok(
          Array.from(document.querySelectorAll('[data-test-pretui-viewport-specimen]')).some(
            (s) => s.childElementCount > 0 || Boolean(s.textContent?.trim()),
          ),
          \`\${name} shows its example\`,
        );
      });
    }
  }
});
`;
}

let expected = render(registries());
if (process.argv.includes('--write')) {
  writeFileSync(TEST, expected);
  console.log(`wrote ${TEST}`);
} else {
  let actual = '';
  try {
    actual = readFileSync(TEST, 'utf8');
  } catch {
    // reported below
  }
  if (actual !== expected) {
    console.error('usage-pages.test.gts is out of date: run `node scripts/usage-proof.mjs --write`.');
    process.exit(1);
  }
}
