import { computeContentHash } from './content-hash.ts';
import {
  LATTICE_GTS_ANALYZER_REVISION,
  LATTICE_GTS_DATA_REVISION_ALGORITHM,
  type LatticeGtsAnalysis,
  type LatticeGtsExportAnalysis,
} from './lattice-gts-analysis-contract.ts';
import type { ClassReference } from './schema-analysis-plugin.ts';

export const LATTICE_GTS_LINKER_REVISION = 'lattice-gts-link-v2';

export type LatticeGtsLinkInput =
  | {
      kind: 'source';
      analysis: LatticeGtsAnalysis;
      // Read from the authoritative source row in the same snapshot, not copied
      // out of analysis JSON. Provider owns authorization and canonical URLs.
      currentSourceRevision: LatticeGtsAnalysis['sourceRevision'];
    }
  | {
      kind: 'trusted';
      fileId: string;
      // A runtime-issued, revision-bound bootstrap contract. Authored source
      // cannot nominate itself as trusted. Provider validates its code closure.
      revision: string;
      exports: string[];
    };

export interface LatticeGtsCodeReceipt {
  version: 1;
  linkerRevision: string;
  runtimeRevision: string;
  root: { fileId: string; name: string };
  // Even a complete dependency closure still requires semantic admission.
  state: 'requires-admission' | 'chrome-data' | 'blocked';
  files: Array<{
    fileId: string;
    kind: 'source' | 'trusted';
    revision: string;
    dataRevision?: LatticeGtsAnalysis['dataRevision'];
    analyzerRevision?: string;
  }>;
  definitions: Array<{ fileId: string; name: string }>;
  diagnostics: Array<{ fileId: string; code: string; message: string }>;
  fingerprint: string;
}

// A bounded pass over FILE-OWNED DATA. No loader, source parser, constructor,
// BXL evaluator, database or network lives here. Callers provide committed
// artifacts and must fence these receipts again when publishing derived data.
// Configured workers consume this classification alongside semantic admission;
// the receipt alone is never permission to execute authored modules in Node.
export async function linkLatticeGtsDefinition({
  root,
  name,
  runtimeRevision,
  read,
  signal,
}: {
  root: LatticeGtsLinkInput;
  name: string;
  runtimeRevision: string;
  read: (
    module: string,
    relativeTo: string,
  ) => Promise<LatticeGtsLinkInput | undefined>;
  signal?: AbortSignal;
}): Promise<LatticeGtsCodeReceipt> {
  const inputs = new Map<string, LatticeGtsLinkInput>();
  const imports = new Map<string, string>();
  const result: Omit<LatticeGtsCodeReceipt, 'fingerprint'> = {
    version: 1,
    linkerRevision: LATTICE_GTS_LINKER_REVISION,
    runtimeRevision,
    root: { fileId: identity(root), name },
    state: 'requires-admission',
    files: [],
    definitions: [],
    diagnostics: [],
  };
  const edge = (fileId: string, specifier: string) =>
    JSON.stringify([fileId, specifier]);
  function issue(
    fileId: string,
    code: string,
    message: string,
    blocked = true,
  ) {
    if (blocked) result.state = 'blocked';
    else if (result.state !== 'blocked') result.state = 'chrome-data';
    if (
      !result.diagnostics.some(
        (item) =>
          item.fileId === fileId &&
          item.code === code &&
          item.message === message,
      )
    )
      result.diagnostics.push({ fileId, code, message });
  }
  function remember(input: LatticeGtsLinkInput): boolean {
    const id = identity(input);
    const revision =
      input.kind === 'source'
        ? input.currentSourceRevision.digest
        : input.revision;
    const old = inputs.get(id);
    if (old) {
      // A provider supplies immutable analyzer output for a source/compiler
      // revision. Compare compact stamps, never serialize whole plans again
      // for each alias or adopting instance.
      if (inputStamp(old) !== inputStamp(input))
        issue(
          id,
          'conflicting-receipts',
          'One file resolved to conflicting artifacts',
        );
      return false;
    }
    if (inputs.size >= 64) throw new Error('Link closure exceeds 64 files');
    inputs.set(id, input);
    result.files.push({
      fileId: id,
      kind: input.kind,
      revision,
      ...(input.kind === 'source'
        ? {
            analyzerRevision: input.analysis.analyzerRevision,
            dataRevision: input.analysis.dataRevision,
          }
        : {}),
    });
    if (!id || !revision) {
      issue(id, 'missing-revision', 'File identity and revision are required');
      return false;
    }
    if (input.kind === 'trusted') return false;
    const analysis = input.analysis;
    if (
      analysis.version !== 1 ||
      analysis.coverage !== 'local-syntax' ||
      analysis.analyzerRevision !== LATTICE_GTS_ANALYZER_REVISION
    ) {
      issue(
        id,
        'analysis-version',
        'Source analysis must be regenerated by the current analyzer',
      );
      return false;
    }
    if (
      analysis.sourceRevision.algorithm !== 'boxel-content-hash-utf8-v1' ||
      analysis.sourceRevision.algorithm !==
        input.currentSourceRevision.algorithm ||
      analysis.sourceRevision.digest !== revision
    ) {
      issue(
        id,
        'stale-analysis',
        'Analysis does not describe the current source revision',
      );
      return false;
    }
    if (analysis.state !== 'analyzed') {
      issue(id, 'blocked-analysis', 'Source analysis is blocked');
      return false;
    }
    for (const diagnostic of analysis.diagnostics)
      issue(id, diagnostic.code, diagnostic.message, false);
    return true;
  }
  type Definition = { fileId: string; name: string; local?: number };
  const key = (item: Definition) =>
    JSON.stringify([item.fileId, item.local ?? item.name]);
  let resolutions = 0;
  function exported(
    fileId: string,
    exportName: string,
    path = new Set<string>(),
  ): Definition[] {
    if (++resolutions > 2048)
      throw new Error('Link closure exceeds 2048 reference resolutions');
    const step = edge(fileId, exportName);
    if (path.has(step)) return [];
    const next = new Set(path).add(step);
    const input = inputs.get(fileId);
    if (!input) return [];
    if (input.kind === 'trusted')
      return input.exports.includes(exportName)
        ? [{ fileId, name: exportName }]
        : [];
    const analysis = input.analysis;
    const declaration = analysis.exports.find(
      (item) => item.name === exportName,
    );
    if (declaration?.target)
      return referenced(fileId, declaration.target, next);
    if (declaration) {
      const local = analysis.localDefinitions.findIndex(
        (item) => item.localName && item.localName === declaration.localName,
      );
      return [{ fileId, name: exportName, ...(local >= 0 ? { local } : {}) }];
    }
    // ESM star exports do not forward default; multiple paths to one original
    // binding are legal, but distinct bindings with the same name are not.
    if (exportName === 'default') return [];
    const candidates = analysis.exportStars.flatMap((specifier) => {
      const target = imports.get(edge(fileId, specifier));
      return target ? exported(target, exportName, next) : [];
    });
    return [...new Map(candidates.map((item) => [key(item), item])).values()];
  }
  function referenced(
    fileId: string,
    ref: ClassReference,
    path?: Set<string>,
  ): Definition[] {
    if (ref.type === 'external') {
      const target = imports.get(edge(fileId, ref.module));
      return target ? exported(target, ref.name, path) : [];
    }
    const input = inputs.get(fileId);
    const local = ref.classIndex;
    const declaration =
      input?.kind === 'source' && local != null
        ? input.analysis.localDefinitions[local]
        : undefined;
    return declaration ? [{ fileId, name: declaration.name, local }] : [];
  }
  try {
    signal?.throwIfAborted();
    if (!runtimeRevision)
      throw new Error('A runtime/compiler revision is required');
    const pending = remember(root) ? [root] : [];
    let requests = 0;
    for (const input of pending) {
      if (input.kind !== 'source') continue;
      const id = identity(input);
      for (const dependency of input.analysis.imports) {
        signal?.throwIfAborted();
        if (dependency.typeOnly || imports.has(edge(id, dependency.module)))
          continue;
        if (++requests > 512)
          throw new Error('Link closure exceeds 512 import reads');
        const loaded = await read(dependency.module, id);
        signal?.throwIfAborted();
        if (!loaded) {
          issue(
            id,
            'missing-import',
            `No current authorized artifact for ${dependency.module}`,
          );
          continue;
        }
        imports.set(edge(id, dependency.module), identity(loaded));
        if (remember(loaded)) pending.push(loaded);
      }
    }
    // Stale or missing artifacts cannot establish a coherent definition graph.
    if (result.state !== 'blocked') {
      const queue: Definition[] = [];
      const schedule = (fileId: string, refs: Definition[], label: string) => {
        if (refs.length !== 1)
          issue(
            fileId,
            refs.length ? 'ambiguous-export' : 'unresolved-definition',
            label,
          );
        else queue.push(refs[0]);
      };
      schedule(result.root.fileId, exported(result.root.fileId, name), name);
      const seen = new Set<string>();
      for (const ref of queue) {
        signal?.throwIfAborted();
        if (seen.has(key(ref))) continue;
        if (seen.size >= 256)
          throw new Error('Link closure exceeds 256 definitions');
        seen.add(key(ref));
        result.definitions.push({ fileId: ref.fileId, name: ref.name });
        const input = inputs.get(ref.fileId)!;
        if (input.kind === 'trusted') continue;
        const declaration: LatticeGtsExportAnalysis =
          ref.local == null
            ? input.analysis.exports.find((item) => item.name === ref.name)!
            : input.analysis.localDefinitions[ref.local];
        if (declaration.indexing !== 'requires-linking') {
          issue(
            ref.fileId,
            'definition-runtime',
            `${ref.name}: ${declaration.indexing}`,
            declaration.indexing === 'blocked',
          );
          for (const reason of declaration.reasons)
            issue(
              ref.fileId,
              reason.code,
              `${ref.name}: ${reason.message}`,
              declaration.indexing === 'blocked',
            );
        }
        const references = [
          ...(declaration.extends ? [declaration.extends] : []),
          ...declaration.fields.flatMap((field) => [
            field.type,
            field.value,
            field.decorator,
          ]),
        ];
        for (const reference of references)
          schedule(
            ref.fileId,
            referenced(ref.fileId, reference),
            `${ref.name}: ${JSON.stringify(reference)}`,
          );
      }
    }
  } catch (error) {
    signal?.throwIfAborted();
    issue(result.root.fileId, 'link-error', String((error as Error).message));
  }
  result.files.sort((a, b) => compare(a.fileId, b.fileId));
  result.definitions.sort((a, b) =>
    compare(JSON.stringify(a), JSON.stringify(b)),
  );
  result.diagnostics.sort((a, b) =>
    compare(JSON.stringify(a), JSON.stringify(b)),
  );
  // Small bounded receipt, not the source, AST, or BXL programs. It can be
  // shared by every card adopting this export. Never use it as a bearer token.
  // Source revisions remain in the receipt and publication scope for exact
  // byte/permission fences. Only a complete declarative plan may identify its
  // data separately from its templates. Unknown code keeps byte invalidation.
  const canReuseData =
    result.state === 'requires-admission' &&
    result.files.every(
      (file) =>
        file.kind === 'trusted' ||
        (file.dataRevision?.algorithm === LATTICE_GTS_DATA_REVISION_ALGORITHM &&
          Boolean(file.dataRevision.digest)),
    );
  const dataIdentity = canReuseData
    ? {
        ...result,
        files: result.files.map(({ revision, dataRevision, ...file }) => ({
          ...file,
          revision: file.kind === 'trusted' ? revision : dataRevision!.digest,
          ...(dataRevision ? { algorithm: dataRevision.algorithm } : {}),
        })),
      }
    : result;
  return {
    ...result,
    fingerprint: computeContentHash(JSON.stringify(dataIdentity)),
  };
}

function identity(input: LatticeGtsLinkInput): string {
  return input.kind === 'source' ? input.analysis.fileId : input.fileId;
}

function inputStamp(input: LatticeGtsLinkInput): string {
  return JSON.stringify(
    input.kind === 'source'
      ? [
          input.kind,
          input.currentSourceRevision.algorithm,
          input.currentSourceRevision.digest,
          input.analysis.sourceRevision.algorithm,
          input.analysis.sourceRevision.digest,
          input.analysis.version,
          input.analysis.coverage,
          input.analysis.analyzerRevision,
          input.analysis.state,
        ]
      : [input.kind, input.revision, [...input.exports].sort()],
  );
}

function compare(a: string, b: string) {
  return a < b ? -1 : a > b ? 1 : 0;
}
