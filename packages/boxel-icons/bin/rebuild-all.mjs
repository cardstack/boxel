import { execFileSync } from 'child_process';
import { createHash } from 'node:crypto';
import fs from 'fs';
import path from 'path';
import { optimize } from 'svgo';

const srcDirs = [
  new URL('../node_modules/@lucide/lab/icons', import.meta.url).pathname,
  new URL('../node_modules/lucide-static/icons', import.meta.url).pathname,
  new URL('../node_modules/@tabler/icons/icons/outline', import.meta.url)
    .pathname,
];

const destDir = new URL('../src', import.meta.url).pathname;
const iconsDestDir = new URL('../src/icons', import.meta.url).pathname;
// Optional raw names allow a focused regeneration without changing the catalog.
const selectedNames = new Set(process.argv.slice(2));

const PREFIX = `
// This file is auto-generated by 'pnpm rebuild:all'
import type { TemplateOnlyComponent } from '@ember/component/template-only';

import type { Signature } from '../types.ts';

const IconComponent: TemplateOnlyComponent<Signature> = <template>
`;
const SUFFIX = `
</template>;

// @ts-expect-error this is the only way to set a name on a Template Only Component currently
IconComponent.name = "__ICON_COMPONENT_NAME__";
Object.defineProperty(IconComponent, Symbol.for('boxel:static-icon-svg'), {
  value: Object.freeze(__STATIC_ICON_SVG__),
});
export default IconComponent;
`;
let componentsToGenerate = [];
for (const srcDir of srcDirs) {
  let batch = fs
    .readdirSync(srcDir)
    .filter((filename) => filename.endsWith('.svg'))
    .map((filename) => {
      return {
        name: toPascalCase(path.parse(filename).name),
        rawName: path.parse(filename).name,
        sourceFile: filename,
        fullPath: path.resolve(srcDir, filename),
        outFile: filename.replace('.svg', '.gts'),
      };
    });
  batch = batch.filter(
    (c) => !componentsToGenerate.find((c2) => c2.rawName === c.rawName),
  );
  componentsToGenerate = componentsToGenerate.concat(batch);
}
componentsToGenerate.sort((a, b) => a.name.localeCompare(b.name));
for (const name of selectedNames) {
  if (!componentsToGenerate.some((c) => c.rawName === name)) {
    throw new Error(`Unknown icon: ${name}`);
  }
}
const generatedFiles = [];

for (const c of componentsToGenerate) {
  if (selectedNames.size && !selectedNames.has(c.rawName)) continue;
  let contents = fs.readFileSync(c.fullPath, 'utf-8');
  contents = optimize(contents, {
    path: c.fullPath,
    plugins: [
      {
        name: 'preset-default',
        params: {
          overrides: {
            removeTitle: false,
            removeDesc: { removeAny: false },
            removeViewBox: false,
          },
        },
      },
    ],
  }).data;
  const artifact = {
    svg: contents,
    contentHash: createHash('md5').update(contents).digest('hex'),
  };
  contents = contents.replace(/<svg(.*?)>/, '<svg$1 ...attributes>');
  let suffix = SUFFIX.replace('__ICON_COMPONENT_NAME__', c.rawName).replace(
    '__STATIC_ICON_SVG__',
    () => JSON.stringify(artifact),
  );
  contents = `${PREFIX}${contents}${suffix}`;
  const outPath = path.resolve(iconsDestDir, c.outFile);
  fs.writeFileSync(outPath, contents);
  generatedFiles.push(outPath);
}

if (selectedNames.size) {
  execFileSync('pnpm', ['exec', 'prettier', '-w', ...generatedFiles]);
  process.exit(0);
}

// Distinct raw names can collide once PascalCased (lucide ships some icons
// under both an old and a new name, e.g. arrow-down-0-1 and arrow-down-01).
// Every file is still generated and importable by path, but the meta module
// needs unique identifiers, so only the first of each collision is listed.
let componentsForMeta = [];
let seenNames = new Set();
for (const c of componentsToGenerate) {
  if (seenNames.has(c.name)) {
    continue;
  }
  seenNames.add(c.name);
  componentsForMeta.push(c);
}

let metaContents = `// This file is auto-generated by 'pnpm rebuild'

import type { Icon } from './types.ts';

`;
metaContents += componentsForMeta
  .map((c) => `import ${c.name} from './icons/${c.outFile}';`)
  .join('\n');
metaContents += '\n\n';
let componentNameArray = componentsForMeta.map((c) => c.name);
metaContents += `export const ALL_ICON_COMPONENTS = [\n  ${componentNameArray.join(
  ',\n  ',
)},\n];\n`;
metaContents += `export {\n  type Icon,\n  ${componentNameArray.join(
  ',\n  ',
)},\n};\n`;
fs.writeFileSync(path.resolve(destDir, 'boxel-icons-meta.ts'), metaContents);

execFileSync('pnpm', ['exec', 'prettier', '-w', `${destDir}/**/*{.ts,.gts}`]);

function toPascalCase(text) {
  return text.replace(/(^\w|-\w)/g, clearAndUpper);
}

function clearAndUpper(text) {
  return text.replace(/-/, '').toUpperCase();
}
