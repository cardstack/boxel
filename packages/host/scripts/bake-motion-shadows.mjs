// Ambient CSS 3.0.1 calibration, adapted from native-boxel's token baker.
// The formulas run at build time only. See vendor/ambientcss-LICENSE.txt.
import { readFileSync, writeFileSync } from 'node:fs';
import prettier from 'prettier';

const output = new URL(
  '../app/styles/motion-shadow-tokens.css',
  import.meta.url,
);
const round = (n) => Math.round(n * 1000) / 1000;
const layer = (y, blur, spread, alpha) =>
  `0 ${round(y / 16)}rem ${round(blur / 16)}rem ${round(spread / 16)}rem rgb(0 0 0 / ${round(alpha)})`;

function shadow(elevation, thickness, strength = 1) {
  let gate = Math.min(elevation + thickness, 1);
  let body = Math.min(thickness, 1);
  // Fixed top lamp, key .9 / fill .7, calibrated elevation range 0..3.
  let far =
    gate *
    (0.2 * 0.13 -
      elevation * 0.077 +
      0.368 -
      body * Math.max(0, 1 - elevation) * 0.14);
  let layers = [
    layer(
      elevation * 6.8 + thickness * 3.8,
      elevation * 4.8 + thickness * 2.7,
      0.8,
      far * strength,
    ),
  ];
  let sweep =
    gate * body * Math.max(0, 1 - elevation / 3) * (thickness * 0.02 + 0.047);
  if (sweep >= 0.003) {
    for (let [reach, blur, spread] of [
      [2.85, 2, 0.9],
      [1.9, 1.35, 0.6],
      [0.95, 0.7, 0.3],
    ])
      layers.push(
        layer(
          elevation * 6.8 + thickness * reach,
          elevation * 4.8 + thickness * blur,
          thickness * spread,
          sweep * strength,
        ),
      );
  }
  return layers.join(', ');
}

// Ambient's directional lamp casts below the card. A diffuse fill at the
// boundary also separates its upper edge from the white card underneath.
// Bake it into the contact face, preserving the two-participant motion budget.
const raisedEdge = layer(0, 8, 1, 0.16);

let css = `/* Generated by scripts/bake-motion-shadows.mjs. Ambient CSS 3.0.1 (MIT).
 * Fixed top lamp plus diffuse raised-edge fill. Contact and pool are separate
 * paints; only opacity animates.
 * Regenerate with pnpm exec node scripts/bake-motion-shadows.mjs. */
:root {
  --boxel-motion-contact: ${shadow(0, 0.45)};
  --boxel-motion-lifted-contact: ${raisedEdge}, ${shadow(0, 0.45, 0.3)};
  --boxel-motion-pool: ${shadow(3, 1)};
  --boxel-motion-raised-shadow: var(--boxel-motion-lifted-contact), var(--boxel-motion-pool);
}
`;
css = await prettier.format(css, { parser: 'css' });
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== css)
    throw new Error('Motion shadow tokens are stale; run the baker.');
} else writeFileSync(output, css);
